// Package apicontract loads the OpenAPI description of the api-server HTTP contract and checks
// HTTP responses against it in tests.
//
// The contract is authored as YAML fragments under docs/development/api-contracts/openapi/:
// common.yaml holds the document metadata and shared components, and areas/*.yaml hold the paths
// of one contract area each. Bundle merges them into openapi.yaml, the single file consumers such
// as the dashboard read. This package is the only implementation of that merge, so the committed
// file and the document tests validate against cannot diverge.
//
// This is test support. Production code must not import it: the contract is read from the source
// tree at run time rather than embedded in the binary, and ResponseValidator reports through
// testing.TB.
package apicontract

import (
	"bytes"
	"context"
	"fmt"
	"os"
	"path/filepath"
	"runtime"
	"sort"
	"strings"
	"sync"

	"github.com/getkin/kin-openapi/openapi3"
	"gopkg.in/yaml.v3"
)

// BundledFile is the generated document's file name inside Dir.
const BundledFile = "openapi.yaml"

// bundledHeader marks the generated file so nobody edits it instead of the fragments.
const bundledHeader = "# Code generated by api-server/internal/shared/apicontract from common.yaml and areas/*.yaml.\n" +
	"# DO NOT EDIT. Regenerate with: UPDATE_OPENAPI=1 go test ./internal/shared/apicontract\n"

// topLevelOrder fixes the order of the generated document's top-level keys so the file reads
// like a hand-written OpenAPI document and diffs stay stable. Nested maps are emitted sorted.
var topLevelOrder = []string{"openapi", "info", "servers", "security", "tags", "paths", "components"}

// httpMethods are the path item keys that hold operations; any other key of a path item (for
// example shared parameters) may be defined by only one fragment.
var httpMethods = map[string]bool{
	"get": true, "put": true, "post": true, "delete": true,
	"options": true, "head": true, "patch": true, "trace": true,
}

// Dir returns the directory holding common.yaml, areas/, and the bundled openapi.yaml. It is
// resolved from this source file's location, so tests in any package find the same files no
// matter what their working directory is.
func Dir() string {
	_, file, _, ok := runtime.Caller(0)
	if !ok {
		// runtime.Caller(0) fails only when the binary has no file information, which a test
		// binary built from this source tree always has.
		panic("apicontract: cannot locate the package source directory")
	}
	return filepath.Join(filepath.Dir(file), "..", "..", "..", "docs", "development", "api-contracts", "openapi")
}

// Bundle merges dir/common.yaml and every dir/areas/*.yaml (in file-name order) into one OpenAPI
// document and returns it as YAML with a generated-file header.
//
// A fragment may contain only `tags`, `paths`, and `components`. The merge refuses, rather than
// overrides, anything defined twice: a tag name, a component name within one component section,
// an operation (path plus method), or a non-operation key of a path item. Two fragments may each
// add different methods to the same path.
func Bundle(dir string) ([]byte, error) {
	return bundleAreas(dir, nil)
}

// bundleAreas is Bundle restricted to the named area fragments (file names without .yaml); a nil
// or empty filter bundles every area.
func bundleAreas(dir string, only map[string]bool) ([]byte, error) {
	document, err := readFragment(filepath.Join(dir, "common.yaml"))
	if err != nil {
		return nil, err
	}
	areas, err := filepath.Glob(filepath.Join(dir, "areas", "*.yaml"))
	if err != nil {
		return nil, fmt.Errorf("list contract areas: %w", err)
	}
	sort.Strings(areas)
	for _, path := range areas {
		if len(only) > 0 && !only[strings.TrimSuffix(filepath.Base(path), ".yaml")] {
			continue
		}
		fragment, err := readFragment(path)
		if err != nil {
			return nil, err
		}
		if err := mergeFragment(document, fragment); err != nil {
			return nil, fmt.Errorf("merge %s: %w", filepath.Base(path), err)
		}
	}
	return encodeDocument(document)
}

var (
	loadOnce sync.Once
	loaded   *openapi3.T
	loadErr  error
)

// AreasEnv restricts Load and ResponseValidator to the listed area fragments (comma-separated file
// names under areas/ without .yaml, for example `servers,platforms`). It exists so one area can
// be authored and tested while other areas are incomplete; with it unset every area is loaded,
// which is what the test suite must pass.
const AreasEnv = "APICONTRACT_AREAS"

// Load returns the contract bundled from the fragments in Dir, parsed and validated as OpenAPI.
//
// It reads the fragments rather than the committed openapi.yaml, so a test sees an edited
// fragment without regenerating the bundle; TestBundledFileIsCurrent keeps the committed file in
// step. AreasEnv narrows which fragments are read. The result is cached for the life of the test
// binary and shared: callers must not mutate it.
func Load() (*openapi3.T, error) {
	loadOnce.Do(func() {
		loaded, loadErr = loadDocument(Dir(), areaFilter(os.Getenv(AreasEnv)))
	})
	return loaded, loadErr
}

// areaFilter parses AreasEnv; an empty result means every area.
func areaFilter(value string) map[string]bool {
	areas := map[string]bool{}
	for _, area := range strings.Split(value, ",") {
		if area = strings.TrimSpace(area); area != "" {
			areas[area] = true
		}
	}
	return areas
}

// loadDocument bundles and parses the contract and enforces the authoring rules that kin-openapi
// does not check by itself.
func loadDocument(dir string, only map[string]bool) (*openapi3.T, error) {
	data, err := bundleAreas(dir, only)
	if err != nil {
		return nil, err
	}
	document, err := openapi3.NewLoader().LoadFromData(data)
	if err != nil {
		return nil, fmt.Errorf("parse bundled contract: %w", err)
	}
	// Validation is in-memory work on an already loaded document; no request context exists to
	// propagate in a test helper.
	if err := document.Validate(context.Background()); err != nil {
		return nil, fmt.Errorf("validate bundled contract: %w", err)
	}
	if err := checkComposition(document); err != nil {
		return nil, err
	}
	return document, nil
}

// readFragment decodes one YAML file into plain maps with string keys. Unquoted status codes
// such as `200:` decode as integer keys, so keys are normalized to strings here.
func readFragment(path string) (map[string]any, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, fmt.Errorf("read contract fragment: %w", err)
	}
	var decoded any
	if err := yaml.Unmarshal(data, &decoded); err != nil {
		return nil, fmt.Errorf("decode %s: %w", filepath.Base(path), err)
	}
	normalized := normalizeKeys(decoded)
	document, ok := normalized.(map[string]any)
	if !ok {
		return nil, fmt.Errorf("decode %s: top level is not a mapping", filepath.Base(path))
	}
	return document, nil
}

// normalizeKeys converts every map[any]any produced by the YAML decoder into map[string]any.
func normalizeKeys(value any) any {
	switch typed := value.(type) {
	case map[string]any:
		for key, child := range typed {
			typed[key] = normalizeKeys(child)
		}
		return typed
	case map[any]any:
		converted := make(map[string]any, len(typed))
		for key, child := range typed {
			converted[fmt.Sprint(key)] = normalizeKeys(child)
		}
		return converted
	case []any:
		for index, child := range typed {
			typed[index] = normalizeKeys(child)
		}
		return typed
	default:
		return value
	}
}

// mergeFragment adds one area fragment to document under the rules documented on Bundle.
func mergeFragment(document, fragment map[string]any) error {
	for key, value := range fragment {
		var err error
		switch key {
		case "tags":
			err = mergeTags(document, value)
		case "paths":
			err = mergePaths(document, value)
		case "components":
			err = mergeComponents(document, value)
		default:
			err = fmt.Errorf("unsupported top-level key %q (a fragment may define only tags, paths, and components)", key)
		}
		if err != nil {
			return err
		}
	}
	return nil
}

func mergeTags(document map[string]any, value any) error {
	added, ok := value.([]any)
	if !ok {
		return fmt.Errorf("tags is not a list")
	}
	existing, _ := document["tags"].([]any)
	names := map[string]bool{}
	for _, tag := range existing {
		if entry, ok := tag.(map[string]any); ok {
			names[fmt.Sprint(entry["name"])] = true
		}
	}
	for _, tag := range added {
		entry, ok := tag.(map[string]any)
		if !ok {
			return fmt.Errorf("tag %v is not a mapping", tag)
		}
		name := fmt.Sprint(entry["name"])
		if names[name] {
			return fmt.Errorf("tag %q is already defined", name)
		}
		names[name] = true
		existing = append(existing, entry)
	}
	document["tags"] = existing
	return nil
}

func mergePaths(document map[string]any, value any) error {
	added, ok := value.(map[string]any)
	if !ok {
		return fmt.Errorf("paths is not a mapping")
	}
	paths, _ := document["paths"].(map[string]any)
	if paths == nil {
		paths = map[string]any{}
		document["paths"] = paths
	}
	for path, item := range added {
		addedItem, ok := item.(map[string]any)
		if !ok {
			return fmt.Errorf("path %q is not a mapping", path)
		}
		current, _ := paths[path].(map[string]any)
		if current == nil {
			paths[path] = addedItem
			continue
		}
		for key, operation := range addedItem {
			if _, exists := current[key]; exists {
				if httpMethods[key] {
					return fmt.Errorf("operation %s %s is already defined", key, path)
				}
				return fmt.Errorf("path %q key %q is already defined by another fragment", path, key)
			}
			current[key] = operation
		}
	}
	return nil
}

func mergeComponents(document map[string]any, value any) error {
	added, ok := value.(map[string]any)
	if !ok {
		return fmt.Errorf("components is not a mapping")
	}
	components, _ := document["components"].(map[string]any)
	if components == nil {
		components = map[string]any{}
		document["components"] = components
	}
	for section, entries := range added {
		addedEntries, ok := entries.(map[string]any)
		if !ok {
			return fmt.Errorf("components.%s is not a mapping", section)
		}
		current, _ := components[section].(map[string]any)
		if current == nil {
			current = map[string]any{}
			components[section] = current
		}
		for name, entry := range addedEntries {
			if _, exists := current[name]; exists {
				return fmt.Errorf("components.%s.%s is already defined", section, name)
			}
			current[name] = entry
		}
	}
	return nil
}

// encodeDocument renders the merged document with the fixed top-level order; any top-level key
// outside topLevelOrder follows in sorted order.
func encodeDocument(document map[string]any) ([]byte, error) {
	keys := make([]string, 0, len(document))
	ordered := map[string]bool{}
	for _, key := range topLevelOrder {
		if _, ok := document[key]; ok {
			keys = append(keys, key)
			ordered[key] = true
		}
	}
	var rest []string
	for key := range document {
		if !ordered[key] {
			rest = append(rest, key)
		}
	}
	sort.Strings(rest)
	keys = append(keys, rest...)

	root := &yaml.Node{Kind: yaml.MappingNode}
	for _, key := range keys {
		keyNode := &yaml.Node{}
		keyNode.SetString(key)
		valueNode := &yaml.Node{}
		if err := valueNode.Encode(document[key]); err != nil {
			return nil, fmt.Errorf("encode %s: %w", key, err)
		}
		root.Content = append(root.Content, keyNode, valueNode)
	}

	var out bytes.Buffer
	out.WriteString(bundledHeader)
	encoder := yaml.NewEncoder(&out)
	encoder.SetIndent(2)
	if err := encoder.Encode(root); err != nil {
		return nil, fmt.Errorf("encode bundled contract: %w", err)
	}
	if err := encoder.Close(); err != nil {
		return nil, fmt.Errorf("encode bundled contract: %w", err)
	}
	return out.Bytes(), nil
}

// checkComposition enforces that allOf is used only with a single member, the OpenAPI 3.0 idiom
// for a nullable or described $ref. ResponseValidator closes object schemas to undocumented
// properties, and a multi-member allOf of closed objects would reject every valid instance.
func checkComposition(document *openapi3.T) error {
	var problems []string
	walkSchemas(document, func(name string, schema *openapi3.Schema) {
		if len(schema.AllOf) > 1 {
			problems = append(problems, name)
		}
	})
	if len(problems) > 0 {
		sort.Strings(problems)
		return fmt.Errorf("allOf with more than one member is not allowed (write the object out, or use oneOf): %v", problems)
	}
	return nil
}

// walkSchemas visits every schema reachable from the document's components and operations once,
// passing a location label for error messages.
func walkSchemas(document *openapi3.T, visit func(location string, schema *openapi3.Schema)) {
	seen := map[*openapi3.Schema]bool{}
	var walk func(location string, ref *openapi3.SchemaRef)
	walk = func(location string, ref *openapi3.SchemaRef) {
		if ref == nil || ref.Value == nil || seen[ref.Value] {
			return
		}
		schema := ref.Value
		seen[schema] = true
		visit(location, schema)
		for name, property := range schema.Properties {
			walk(location+"."+name, property)
		}
		walk(location+"[]", schema.Items)
		walk(location+"{}", schema.AdditionalProperties.Schema)
		walk(location+"!", schema.Not)
		for index, member := range schema.AllOf {
			walk(fmt.Sprintf("%s.allOf[%d]", location, index), member)
		}
		for index, member := range schema.OneOf {
			walk(fmt.Sprintf("%s.oneOf[%d]", location, index), member)
		}
		for index, member := range schema.AnyOf {
			walk(fmt.Sprintf("%s.anyOf[%d]", location, index), member)
		}
	}
	if document.Components != nil {
		for name, ref := range document.Components.Schemas {
			walk("#/components/schemas/"+name, ref)
		}
		for name, ref := range document.Components.Responses {
			if ref.Value != nil {
				for mediaType, media := range ref.Value.Content {
					walk("#/components/responses/"+name+" "+mediaType, media.Schema)
				}
			}
		}
		for name, ref := range document.Components.RequestBodies {
			if ref.Value != nil {
				for mediaType, media := range ref.Value.Content {
					walk("#/components/requestBodies/"+name+" "+mediaType, media.Schema)
				}
			}
		}
	}
	if document.Paths == nil {
		return
	}
	for path, item := range document.Paths.Map() {
		for method, operation := range item.Operations() {
			label := method + " " + path
			if operation.RequestBody != nil && operation.RequestBody.Value != nil {
				for mediaType, media := range operation.RequestBody.Value.Content {
					walk(label+" request "+mediaType, media.Schema)
				}
			}
			if operation.Responses == nil {
				continue
			}
			for status, response := range operation.Responses.Map() {
				if response.Value == nil {
					continue
				}
				for mediaType, media := range response.Value.Content {
					walk(label+" "+status+" "+mediaType, media.Schema)
				}
			}
		}
	}
}
